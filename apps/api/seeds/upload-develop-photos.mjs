const sql = readFileSync(join(here, "develop.sql"), "utf8");
const keys = [...sql.matchAll(/\('ph-[^']*', '[^']*', '([^']*)', \d+\)/g)].map((match) => match[1]);

if (keys.length === 0) {
  process.stdout.write("seeds/develop.sql has no product_photos rows; nothing uploaded\n");
  process.exit(0);
}

const safeKey = /^photos\/[a-z0-9-]+\.webp$/;
const rejected = keys.filter((key) => !safeKey.test(key));
if (rejected.length > 0) {
  process.stderr.write(`refusing keys outside photos/*.webp: ${rejected.join(", ")}\n`);
  process.exit(1);
}

const dir = mkdtempSync(join(tmpdir(), "gift-shop-photos-"));
const file = join(dir, "pixel.jpg");
try {
  writeFileSync(file, jpeg);
  for (const key of keys) {
    execFileSync(
      process.execPath,
      [
        wrangler,
        "r2",
        "object",
        "put",
        `${bucket}/${key}`,
        "--file",
        file,
        "--content-type",
        "image/jpeg",
        "--remote",
        "--env",
        "develop",
        "--force",
      ],
      { cwd: apiRoot, stdio: "inherit" },
    );
  }
} finally {
  rmSync(dir, { recursive: true, force: true });
}

process.stdout.write(`uploaded ${keys.length} jpeg objects to ${bucket}\n`);
